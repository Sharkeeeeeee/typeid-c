#!/usr/bin/env python3
"""Generate tests/vectors.h from the official TypeID spec test vectors.

Usage: python3 tools/gen_vectors.py tests/spec tests/vectors.h
"""
import json
import sys
from pathlib import Path


def c_str(s: str) -> str:
    out = []
    for b in s.encode("utf-8"):
        if b < 0x20 or b >= 0x7F or b in (0x22, 0x5C, 0x3F):
            out.append("\\%03o" % b)
        else:
            out.append(chr(b))
    return '"' + "".join(out) + '"'


def main() -> None:
    spec, dest = Path(sys.argv[1]), Path(sys.argv[2])
    valid = json.loads((spec / "valid.json").read_text(encoding="utf-8"))
    invalid = json.loads((spec / "invalid.json").read_text(encoding="utf-8"))
    lines = [
        "/* Generated by tools/gen_vectors.py from the official TypeID spec",
        " * test vectors (https://github.com/jetify-com/typeid/tree/main/spec).",
        " * Do not edit by hand. */",
        "",
        "typedef struct { const char *name, *str, *prefix, *uuid; } valid_vector;",
        "typedef struct { const char *name, *str, *description; } invalid_vector;",
        "",
        "static const valid_vector VALID[] = {",
    ]
    for v in valid:
        lines.append("    {%s, %s, %s, %s}," % tuple(c_str(v[k]) for k in ("name", "typeid", "prefix", "uuid")))
    lines += ["};", "", "static const invalid_vector INVALID[] = {"]
    for v in invalid:
        lines.append("    {%s, %s, %s}," % tuple(c_str(v[k]) for k in ("name", "typeid", "description")))
    lines += ["};", ""]
    dest.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
